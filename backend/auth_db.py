import os
from contextlib import contextmanager

import psycopg2
from psycopg2.extras import RealDictCursor

from werkzeug.security import generate_password_hash, check_password_hash


DATABASE_URL = os.environ.get("DATABASE_URL")


def get_connection():
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL environment variable is not set.")

    return psycopg2.connect(
        DATABASE_URL,
        sslmode="require"
    )


@contextmanager
def db_connection():
    connection = get_connection()

    try:
        with connection.cursor(cursor_factory=RealDictCursor) as cursor:
            yield cursor
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def init_auth_db():
    """Create authentication tables if they do not already exist."""

    with db_connection() as cursor:

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                role TEXT NOT NULL DEFAULT 'user'
                    CHECK (role IN ('admin', 'user')),
                active_dataset_id TEXT NOT NULL DEFAULT 'online_retail',
                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS app_settings (
                setting_key TEXT PRIMARY KEY,
                setting_value TEXT NOT NULL
            )
        """)

        cursor.execute("""
            INSERT INTO app_settings (
                setting_key, setting_value
            )
            VALUES ('registration_open', '0')
            ON CONFLICT (setting_key) DO NOTHING
        """)


def create_user(name, email, password, role="user"):
    """Create a user with a securely hashed password."""

    if role not in ("admin", "user"):
        raise ValueError("Invalid user role.")

    password_hash = generate_password_hash(password)

    with db_connection() as cursor:
        cursor.execute("""
            INSERT INTO users (name, email, password_hash, role)
            VALUES (%s, %s, %s, %s)
            RETURNING id
        """, (
            name.strip(),
            email.strip().lower(),
            password_hash,
            role
        ))

        row = cursor.fetchone()
        return row["id"]


def get_user_by_email(email):
    with db_connection() as cursor:
        cursor.execute("""
            SELECT * FROM users
            WHERE email = %s
        """, (email.strip().lower(),))

        row = cursor.fetchone()
        return dict(row) if row else None


def get_user_by_id(user_id):
    with db_connection() as cursor:
        cursor.execute("""
            SELECT * FROM users
            WHERE id = %s
        """, (user_id,))

        row = cursor.fetchone()
        return dict(row) if row else None


def verify_password(user, password):
    if not user:
        return False

    return check_password_hash(
        user["password_hash"],
        password
    )


def count_admins():
    with db_connection() as cursor:
        cursor.execute("""
            SELECT COUNT(*) AS total
            FROM users
            WHERE role = 'admin'
        """)

        row = cursor.fetchone()
        return row["total"]


def get_active_dataset(user_id):
    with db_connection() as cursor:
        cursor.execute("""
            SELECT active_dataset_id
            FROM users
            WHERE id = %s
        """, (user_id,))

        row = cursor.fetchone()

        if row is None:
            raise ValueError("User not found.")

        return row["active_dataset_id"]


def set_active_dataset(user_id, dataset_id):
    with db_connection() as cursor:
        cursor.execute("""
            UPDATE users
            SET active_dataset_id = %s
            WHERE id = %s
        """, (dataset_id, user_id))

        if cursor.rowcount == 0:
            raise ValueError("User not found.")


def get_setting(key, default=None):
    with db_connection() as cursor:
        cursor.execute("""
            SELECT setting_value
            FROM app_settings
            WHERE setting_key = %s
        """, (key,))

        row = cursor.fetchone()
        return row["setting_value"] if row else default


def set_setting(key, value):
    with db_connection() as cursor:
        cursor.execute("""
            INSERT INTO app_settings (setting_key, setting_value)
            VALUES (%s, %s)
            ON CONFLICT (setting_key)
            DO UPDATE SET setting_value = EXCLUDED.setting_value
        """, (key, str(value)))
